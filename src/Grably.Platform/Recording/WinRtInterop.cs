using System.Runtime.InteropServices;
using Vortice.Direct3D11;
using Vortice.DXGI;
using Windows.Graphics.Capture;
using Windows.Graphics.DirectX.Direct3D11;
using WinRT;

namespace Grably.Platform.Recording;

/// <summary>
/// Every COM and WinRT crossing the screen recorder needs, in one place: Direct3D device to WinRT device, capture
/// items for a monitor or window, and a captured surface back to a Direct3D texture. The COM interfaces involved
/// (IGraphicsCaptureItemInterop, IDirect3DDxgiInterfaceAccess) are not part of the WinRT projection, so they are
/// called through their vtables with function pointers instead of relying on any casting helper.
/// </summary>
internal static partial class WinRtInterop
{
    private static readonly Guid IGraphicsCaptureItemInterop = new("3628E81B-3CAC-4C60-B7F4-23CE0E0C3356");
    private static readonly Guid IGraphicsCaptureItem = new("79C3F95B-31F7-4EC2-A464-632EF5D30760");
    private static readonly Guid IDirect3DDxgiInterfaceAccess = new("A9B3D012-3DF2-4EE3-B8D1-8695F457D3C1");

    /// <summary>The WinRT device that Windows.Graphics.Capture needs, wrapping our Direct3D 11 device.</summary>
    public static IDirect3DDevice CreateWinRtDevice(ID3D11Device device)
    {
        using var dxgi = device.QueryInterface<IDXGIDevice>();
        Marshal.ThrowExceptionForHR(CreateDirect3D11DeviceFromDXGIDevice(dxgi.NativePointer, out var inspectable));
        try
        {
            return MarshalInterface<IDirect3DDevice>.FromAbi(inspectable);
        }
        finally
        {
            Marshal.Release(inspectable);
        }
    }

    public static GraphicsCaptureItem ForMonitor(nint monitor) => CreateItem(monitor, forWindow: false);

    public static GraphicsCaptureItem ForWindow(nint window) => CreateItem(window, forWindow: true);

    /// <summary>The Direct3D texture behind a captured frame's surface (the caller disposes it).</summary>
    public static unsafe ID3D11Texture2D TextureOf(IDirect3DSurface surface)
    {
        var surfacePointer = MarshalInterface<IDirect3DSurface>.FromManaged(surface);
        try
        {
            var access = QueryInterface(surfacePointer, IDirect3DDxgiInterfaceAccess);
            try
            {
                // IDirect3DDxgiInterfaceAccess::GetInterface(REFIID, void**) is the first method after IUnknown.
                var getInterface = (delegate* unmanaged[Stdcall]<nint, Guid*, nint*, int>)(*(void***)access)[3];
                var iid = typeof(ID3D11Texture2D).GUID;
                nint texture;
                Marshal.ThrowExceptionForHR(getInterface(access, &iid, &texture));
                return new ID3D11Texture2D(texture);
            }
            finally
            {
                Marshal.Release(access);
            }
        }
        finally
        {
            Marshal.Release(surfacePointer);
        }
    }

    private static unsafe GraphicsCaptureItem CreateItem(nint handle, bool forWindow)
    {
        var factory = ActivationFactory.Get("Windows.Graphics.Capture.GraphicsCaptureItem");
        var interop = QueryInterface(factory.ThisPtr, IGraphicsCaptureItemInterop);
        try
        {
            // IGraphicsCaptureItemInterop: CreateForWindow(HWND, REFIID, void**), then CreateForMonitor(HMONITOR, REFIID, void**).
            var create = (delegate* unmanaged[Stdcall]<nint, nint, Guid*, nint*, int>)(*(void***)interop)[forWindow ? 3 : 4];
            var iid = IGraphicsCaptureItem;
            nint item;
            Marshal.ThrowExceptionForHR(create(interop, handle, &iid, &item));
            try
            {
                return GraphicsCaptureItem.FromAbi(item);
            }
            finally
            {
                Marshal.Release(item);
            }
        }
        finally
        {
            Marshal.Release(interop);
        }
    }

    private static nint QueryInterface(nint unknown, Guid iid)
    {
        Marshal.ThrowExceptionForHR(Marshal.QueryInterface(unknown, in iid, out var result));
        return result;
    }

    // Not generated by CsWin32 on purpose: its projection would hand back its own COM types, while the device here
    // is a Vortice object; the raw pointer is the common ground.
    [LibraryImport("d3d11.dll")]
    private static partial int CreateDirect3D11DeviceFromDXGIDevice(nint dxgiDevice, out nint graphicsDevice);
}
